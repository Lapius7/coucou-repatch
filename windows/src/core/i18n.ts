const dictionaries: Record<string, Record<string, string>> = { en, ja };

let active = "en";

/** "auto" follows Windows; otherwise the code itself. Unknown codes fall back to English. */
export function resolveLanguage(setting: string): string {
  const code = setting === "auto" ? (navigator.language || "en").slice(0, 2).toLowerCase() : setting;
  return dictionaries[code] ? code : "en";
}

export function setLanguage(setting: string) {
  active = resolveLanguage(setting);
  document.documentElement.lang = active;
}

export function currentLanguage(): string {
  return active;
}

/** The text for `key`, with `{name}` filled in and a count picked for "one|other". */
export function t(key: string, vars?: Record<string, string | number>): string {
  let text = dictionaries[active]?.[key] ?? en[key] ?? key;
  if (vars) {
    if (text.includes("|") && typeof vars.n === "number") {
      const [one, other] = text.split("|");
      text = vars.n === 1 ? one : (other ?? one);
    }
    text = text.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
  }
  return text;
}
